def class_distribution_figure(meta: dict, out: Path) -> None:
    """Training flows per class (log scale), minority classes highlighted, with the 1% threshold."""
    from matplotlib.patches import Patch
    counts = pd.Series(meta["class_counts"]["train"]).sort_values()
    minority = {meta["classes"][i] for i in meta["minority"]}
    colors = ["#eb6834" if c in minority else "#2a78d6" for c in counts.index]
    fig, ax = plt.subplots(figsize=(3.45, 4.8))
    ax.barh(range(len(counts)), counts.to_numpy(), color=colors, height=0.72)
    ax.set_yticks(range(len(counts)), [CIC_NAMES.get(c, c) for c in counts.index], fontsize=5.5)
    ax.tick_params(axis="x", labelsize=7)
    ax.set_ylim(-1.6, len(counts) - 0.4)
    ax.set_xscale("log")
    ax.set_xlabel("Training flows (log scale)", fontsize=8)
    ax.grid(axis="y", visible=False)
    threshold = 0.01 * counts.sum()
    ax.axvline(threshold, color=INK_2, linestyle="--", linewidth=1)
    ax.text(threshold * 1.08, -1.2, "1% of training flows", color=INK_2, fontsize=6.5, va="center")
    fig.legend(handles=[Patch(color="#2a78d6", label="Class"),
                        Patch(color="#eb6834", label=f"Minority class (< 1%, {len(minority)} classes)")],
               loc="upper center", ncol=1, frameon=False, fontsize=7)
    fig.tight_layout(rect=(0, 0, 1, 0.92))
    fig.savefig(out)
    plt.close(fig)
    print(f"wrote {out}")


def confidence_by_category_figure(pool, pool_dir: Path, out: Path, model: str = "decision_tree_l256_f20") -> None:
    """Confidence of a device-tier detector by predicted category, for correct and wrong predictions
    (validation split): why one global escalation threshold cannot fit every category."""
    meta = load_json(pool_dir / "pool.json")
    category_of_class = np.array(meta["categories"])
    i = pool.names.index(model)
    pred = pool.pred["val"][i].astype(np.int64)
    conf = pool.conf["val"][i].astype(np.float32)
    correct = pred == pool.y["val"].astype(np.int64)
    pred_cat = category_of_class[pred]
    order = [c for c in ["Benign", "DDoS", "DoS", "Mirai", "Recon", "Spoofing", "Web", "BruteForce"]
             if c in set(pred_cat)]
    fig, ax = plt.subplots(figsize=(3.45, 2.8))
    pos = np.arange(len(order))
    for offset, ok, color, label in ((-0.2, True, "#2a78d6", "Correct prediction"),
                                     (0.2, False, "#eb6834", "Wrong prediction")):
        data = [conf[(pred_cat == c) & (correct == ok)] for c in order]
        bp = ax.boxplot(data, positions=pos + offset, widths=0.34, patch_artist=True, showfliers=False,
                        medianprops={"color": "white", "linewidth": 1.4},
                        whiskerprops={"color": color}, capprops={"color": color})
        for box in bp["boxes"]:
            box.set(facecolor=color, edgecolor=color)
        ax.plot([], [], color=color, linewidth=6, label=label)
    wrong_share = [100 * np.mean(~correct[pred_cat == c]) for c in order]
    short = {"BruteForce": "Brute\nforce", "Spoofing": "Spoof."}
    ax.set_xticks(pos, [f"{short.get(c, c)}\n{w:.0f}%" for c, w in zip(order, wrong_share)], fontsize=6)
    ax.tick_params(axis="y", labelsize=7)
    ax.set_ylabel("Confidence $q$", fontsize=8)
    ax.set_ylim(0, 1.02)
    ax.grid(axis="x", visible=False)
    fig.legend(*ax.get_legend_handles_labels(), loc="upper center", ncol=2, frameon=False, fontsize=7)
    fig.tight_layout(rect=(0, 0, 1, 0.92))
    fig.savefig(out)
    plt.close(fig)
    print(f"wrote {out}")



