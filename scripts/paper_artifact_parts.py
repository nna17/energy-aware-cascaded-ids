def search_study_table(df: pd.DataFrame, out: Path) -> None:
    a = df[df.selection == "archive"]
    final = a[a.evaluations == a.evaluations.max()]
    txs = sorted(final.tx.unique())
    stats = final.groupby(["variant", "tx"]).hv_log_cost.agg(["mean", "std"])
    curve = a.groupby(["variant", "tx", "evaluations"]).hv_log_cost.mean()
    n_seeds = final.groupby(["variant", "tx"]).size().min()

    def reach(variant: str, tx: float) -> str:
        target = stats.loc[("random_ordered", tx), "mean"]
        c = curve.loc[(variant, tx)]
        hit = c[c >= target]
        return fmt_int(hit.index.min()) if len(hit) else "--"

    rows = []
    for key, (label, _, _) in ALGOS.items():
        cells = []
        for tx in txs:
            m, s = stats.loc[(key, tx), "mean"], stats.loc[(key, tx), "std"]
            rel = "--" if key == "random_ordered" else f"{100 * (m / stats.loc[('random_ordered', tx), 'mean'] - 1):+.1f}\\%"
            cells += [f"{m:.4f} $\\pm$ {s:.4f}", rel, reach(key, tx)]
        secs = df[df.variant == key].seconds.mean()
        rows.append(f"{label} & " + " & ".join(cells) + f" & {secs:.0f} \\\\")
    head = " & ".join(rf"\multicolumn{{3}}{{c}}{{Transmission cost {fmt_int(tx)}}}" for tx in txs)
    sub = " & ".join(r"HV (log cost) & vs.\ random & \makecell{evals to match\\random@10k}" for _ in txs)
    rules = " ".join(rf"\cmidrule(lr){{{2 + 3 * i}-{4 + 3 * i}}}" for i in range(len(txs)))
    write(out, rf"""\begin{{table*}}[t]
\centering
\caption{{Search algorithms with an equal budget of {fmt_int(a.evaluations.max())} evaluations, results taken from each algorithm's full archive (test split, mean $\pm$ std over {n_seeds} search seeds). The last column of each block is the smallest budget at which the algorithm reaches random search's final hypervolume.}}
\label{{tab:search}}
\resizebox{{\textwidth}}{{!}}{{%
\begin{{tabular}}{{@{{}}l{'ccc' * len(txs)}r@{{}}}}
\toprule
 & {head} & \\
{rules}
Algorithm & {sub} & Time (s) \\
\midrule
{chr(10).join(rows)}
\bottomrule
\end{{tabular}}}}
\end{{table*}}
""")


def search_curve_figure(df: pd.DataFrame, out: Path) -> None:
    a = df[df.selection == "archive"]
    txs = sorted(a.tx.unique())
    budgets = sorted(a.evaluations.unique())
    pos = {b: i for i, b in enumerate(budgets)}
    fig, axes = plt.subplots(1, len(txs), figsize=(3.45, 2.7))
    for ax, tx in zip(np.atleast_1d(axes), txs):
        for j, (key, (label, color, marker)) in enumerate(ALGOS.items()):
            g = a[(a.variant == key) & (a.tx == tx)].groupby("evaluations").hv_log_cost.agg(["mean", "std"])
            x = np.array([pos[b] for b in g.index]) + (j - 2) * 0.07  # small dodge so error bars stay readable
            ax.errorbar(x, g["mean"], yerr=g["std"], color=color, marker=marker, markersize=4.5,
                        linewidth=1.5, capsize=2, markeredgecolor="white", markeredgewidth=0.5, label=label)
        ax.set_xticks(range(len(budgets)), [f"{b // 1000:g}k" for b in budgets], fontsize=6.5)
        ax.tick_params(axis="y", labelsize=6.5)
        ax.set_xlim(-0.35, len(budgets) - 0.65)
        ax.set_xlabel("Evaluations", fontsize=8)
        ax.set_title(f"$t = {fmt_int(tx)}$", loc="left", color=INK, fontsize=8)
    np.atleast_1d(axes)[0].set_ylabel("Hypervolume (log cost)", fontsize=8)
    handles, labels = np.atleast_1d(axes)[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper center", ncol=2, frameon=False, fontsize=6.5)
    fig.tight_layout(rect=(0, 0, 1, 0.78), w_pad=0.6)
    fig.savefig(out)
    plt.close(fig)
    print(f"wrote {out}")


